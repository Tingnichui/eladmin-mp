-- 独立电子借条主表，双方通过身份证号HMAC-SHA256值逻辑关联iou_user。
-- HMAC规则与密钥必须与用户表一致；不设外键，允许对方尚未注册。
-- 服务费由借款人支付，支付状态保存在独立服务费订单表。
-- 在eladmin数据库执行；重复执行不会覆盖已有表或数据。
USE `eladmin`;
SET NAMES utf8mb4;

CREATE TABLE IF NOT EXISTS `iou_note` (
  `id` bigint NOT NULL AUTO_INCREMENT COMMENT '借条ID',
  `note_no` varchar(32) NOT NULL COMMENT '借条编号',
  `creator_user_id` bigint NOT NULL COMMENT '发起人用户ID，逻辑关联iou_user.id',
  `borrower_name` varchar(64) DEFAULT NULL COMMENT '借款人姓名快照，对方签署前可为空',
  `borrower_id_no_hash` char(64) CHARACTER SET ascii COLLATE ascii_bin DEFAULT NULL COMMENT '借款人身份证HMAC-SHA256值，逻辑关联iou_user.id_no_hash',
  `borrower_id_no_encrypted` varchar(512) DEFAULT NULL COMMENT '借款人身份证号密文快照',
  `lender_name` varchar(64) DEFAULT NULL COMMENT '出借人姓名快照，对方签署前可为空',
  `lender_id_no_hash` char(64) CHARACTER SET ascii COLLATE ascii_bin DEFAULT NULL COMMENT '出借人身份证HMAC-SHA256值，逻辑关联iou_user.id_no_hash',
  `lender_id_no_encrypted` varchar(512) DEFAULT NULL COMMENT '出借人身份证号密文快照',
  `loan_type` tinyint NOT NULL DEFAULT 1 COMMENT '借款类型：1单次借款，2分期借款',
  `principal_amount` decimal(18,2) NOT NULL COMMENT '借款本金',
  `annual_rate` decimal(12,8) NOT NULL DEFAULT 0 COMMENT '年利率，0.15表示15%',
  `loan_date` date NOT NULL COMMENT '借款日期',
  `due_date` date NOT NULL COMMENT '最终还款日期',
  `interest_amount` decimal(18,2) NOT NULL COMMENT '总利息',
  `total_amount` decimal(18,2) NOT NULL COMMENT '应还本金加利息',
  `purpose` varchar(255) DEFAULT NULL COMMENT '借款用途',
  `remark` varchar(500) DEFAULT NULL COMMENT '备注',
  `service_fee` decimal(18,2) NOT NULL DEFAULT 0 COMMENT '借款人应付服务费',
  `borrower_signed_at` datetime DEFAULT NULL COMMENT '借款人签署时间',
  `lender_signed_at` datetime DEFAULT NULL COMMENT '出借人签署时间',
  `agreement_file` varchar(255) DEFAULT NULL COMMENT '协议文件存储标识',
  `status` tinyint NOT NULL DEFAULT 0 COMMENT '借条状态：0草稿，1待对方确认，2已生效，3已结清，4已取消，5已拒绝，6待支付服务费，7待对方签署',
  `effective_at` datetime DEFAULT NULL COMMENT '生效时间',
  `cancel_reason` varchar(255) DEFAULT NULL COMMENT '取消原因',
  `create_time` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  `update_time` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
  -- 发起与签署扩展字段：旧记录不自动伪造角色、计划或签署凭证。
  `creator_role` tinyint DEFAULT NULL COMMENT '发起人身份：1借款人，2出借人，旧记录可为空',
  `repayment_method` varchar(16) DEFAULT NULL COMMENT 'once/annuity/principal/interest/flat/custom',
  `installment_count` int DEFAULT NULL COMMENT '约定还款期数，一次性为1',
  `repayment_cycle_months` int DEFAULT NULL COMMENT '标准还款周期月数，自定义可为空',
  `first_due_date` date DEFAULT NULL COMMENT '首期还款日期',
  `interest_rule` varchar(32) DEFAULT NULL COMMENT '计息规则标识',
  `calculation_version` varchar(32) DEFAULT NULL COMMENT '后端计算规则版本',
  `prepayment_rule` varchar(32) DEFAULT NULL COMMENT '提前还款规则标识',
  `overdue_terms` varchar(1000) DEFAULT NULL COMMENT '逾期约定正文',
  `terms_snapshot` longtext COMMENT '发起人签署的条款与完整还款计划快照，内部使用',
  `terms_hash` char(64) CHARACTER SET ascii COLLATE ascii_bin DEFAULT NULL COMMENT '规范化条款快照SHA256',
  `terms_locked_at` datetime DEFAULT NULL COMMENT '开始签署时锁定条款时间',
  `borrower_sign_status` tinyint NOT NULL DEFAULT 0 COMMENT '借款人签署：0未发起，1处理中，2成功，3失败',
  `borrower_sign_request_id` varchar(128) DEFAULT NULL COMMENT '借款人签署请求ID，内部使用',
  `borrower_sign_evidence_id` varchar(255) DEFAULT NULL COMMENT '借款人签署凭证标识，内部使用',
  `borrower_sign_file` varchar(512) DEFAULT NULL COMMENT '借款人签署文件存储标识，内部使用',
  `borrower_sign_file_hash` char(64) CHARACTER SET ascii COLLATE ascii_bin DEFAULT NULL COMMENT '借款人签署文件SHA256',
  `lender_sign_status` tinyint NOT NULL DEFAULT 0 COMMENT '出借人签署：0未发起，1处理中，2成功，3失败',
  `lender_sign_request_id` varchar(128) DEFAULT NULL COMMENT '出借人签署请求ID，内部使用',
  `lender_sign_evidence_id` varchar(255) DEFAULT NULL COMMENT '出借人签署凭证标识，内部使用',
  `lender_sign_file` varchar(512) DEFAULT NULL COMMENT '出借人签署文件存储标识，内部使用',
  `lender_sign_file_hash` char(64) CHARACTER SET ascii COLLATE ascii_bin DEFAULT NULL COMMENT '出借人签署文件SHA256',
  `agreement_hash` char(64) CHARACTER SET ascii COLLATE ascii_bin DEFAULT NULL COMMENT '最终协议文件SHA256',
  `row_version` bigint NOT NULL DEFAULT 0 COMMENT '并发版本号，由条件更新推进',
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_iou_note_note_no` (`note_no`),
  KEY `idx_iou_note_borrower_status` (`borrower_id_no_hash`, `status`),
  KEY `idx_iou_note_lender_status` (`lender_id_no_hash`, `status`),
  KEY `idx_iou_note_creator` (`creator_user_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='电子借条主表';
